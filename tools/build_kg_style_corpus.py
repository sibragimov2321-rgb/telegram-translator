URL_RE = re.compile(r"(?i)\b(?:https?://|www\.|t\.me/|telegram\.me/)\S+")
EMAIL_RE = re.compile(r"(?i)\b[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}\b")
USERNAME_RE = re.compile(r"(?<!\w)@[A-Za-z0-9_]{4,}")
PHONE_RE = re.compile(r"(?<!\w)\+?\d[\d ()-]{7,}\d(?!\w)")
LONG_ID_RE = re.compile(r"\d{7,}")
TOKEN_RE = re.compile(r"[0-9A-Za-zА-Яа-яЁёҢңӨөҮүҚқҒғҺһ]+", re.UNICODE)
CYRILLIC_RE = re.compile(r"[А-Яа-яЁёҢңӨөҮүҚқҒғҺһ]", re.UNICODE)
EMOJI_RE = re.compile("[\U0001F300-\U0001FAFF\u2600-\u27BF]")

